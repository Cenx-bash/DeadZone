use macroquad::prelude::*;

#[derive(Clone, Copy, PartialEq, Eq)]
pub enum WeaponCategory {
    Primary,
    Secondary,
    Melee,
}

impl WeaponCategory {
    pub fn of(idx: usize) -> WeaponCategory {
        match idx {
            0 | 7 => WeaponCategory::Secondary,
            1 => WeaponCategory::Melee,
            _ => WeaponCategory::Primary,
        }
    }
}

#[derive(Clone, Copy, PartialEq)]
pub enum Rarity {
    Common,
    Uncommon,
    Rare,
    Epic,
    Legendary,
}

impl Rarity {
    pub fn color(self) -> Color {
        match self {
            Rarity::Common => Color::new(0.70, 0.70, 0.70, 1.0),
            Rarity::Uncommon => Color::new(0.30, 0.90, 0.40, 1.0),
            Rarity::Rare => Color::new(0.30, 0.60, 1.00, 1.0),
            Rarity::Epic => Color::new(0.70, 0.40, 1.00, 1.0),
            Rarity::Legendary => Color::new(1.00, 0.80, 0.20, 1.0),
        }
    }
    pub fn name(self) -> &'static str {
        match self {
            Rarity::Common => "COMMON",
            Rarity::Uncommon => "UNCOMMON",
            Rarity::Rare => "RARE",
            Rarity::Epic => "EPIC",
            Rarity::Legendary => "LEGENDARY",
        }
    }
}

