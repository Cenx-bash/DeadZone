pub fn is_attachment_compatible(weapon_idx: usize, attachment_idx: usize) -> bool {
    use crate::weapons::attachments::ATTACHMENTS;
    if attachment_idx >= ATTACHMENTS.len() {
        return false;
    }
    let slot = ATTACHMENTS[attachment_idx].slot;
    compatible_attachments(weapon_idx, slot).contains(&attachment_idx)
}
